           "type=%s k_of=(%d,%d) trans=%d", ename(r.type), spec::k_of(r.type, false),
           spec::k_of(r.type, true), spec::trans_allowed(r.type) ? 1 : 0);
    for (int n = 0; n <= 264; ++n) {
      bool listed = false;
