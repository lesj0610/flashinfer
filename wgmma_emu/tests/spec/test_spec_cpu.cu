// Figures 151/153/155/157 (dense A) and 178/180/182 (sparse A).
void test_fig_a(bool sparse) {
  Test t = make_test(sparse ? "a_fig_a_sparse" : "a_fig_a_dense");
  for (int fi = 0; fi < fig::kNumAFigs; ++fi) {
    const fig::AFig& f = fig::kAFigs[fi];
    if (f.sparse != sparse) continue;
    for (int ti = 0; ti < f.ntypes; ++ti) {
      const EType at = f.types[ti];
      const int epr = spec::a_elems_per_reg(at);
      const int K = spec::k_of(at, sparse);
      expect(t, f.cell_elems == epr, "fig=%d type=%s cell_elems=%d a_elems_per_reg=%d", f.fig,
             ename(at), f.cell_elems, epr);
      expect(t, 4 * f.cell_cols == f.right_col0, "fig=%d type=%s cell_cols=%d right_col0=%d", f.fig,
             ename(at), f.cell_cols, f.right_col0);
      expect(t, 2 * f.right_col0 == K, "fig=%d type=%s right_col0=%d k_of=%d", f.fig, ename(at),
             f.right_col0, K);
      if (sparse) {
        expect(t, f.cell_cols == 2 * f.cell_elems, "fig=%d type=%s cell_cols=%d cell_elems=%d",
               f.fig, ename(at), f.cell_cols, f.cell_elems);
      }
      for (int ri = 0; ri < fig::kNumFragRows; ++ri) {
        const fig::FragRow& row = fig::kFragRows[ri];
        for (int half = 0; half < 2; ++half) {
          for (int q = 0; q < 4; ++q) {
            const int thr = row.t_first + q;
            const int col0 = half * f.right_col0 + q * f.cell_cols;
            for (int s = 0; s < f.cell_elems; ++s) {
              const int x = f.first[row.group][half] + s;
              const int j = x / epr, e = x % epr;
              int m = -1, k = -1, want_k;
              if (!sparse) {
                spec::a_frag_coord(at, thr, j, e, &m, &k);
                want_k = col0 + s;
              } else {
                spec::sp_a_frag_coord(at, thr, j, e, &m, &k);
                want_k = col0 / 2 + s;
              }
              expect(t, m == row.row && k == want_k,
                     "fig=%d type=%s t=%d a%d (reg %d elem %d) spec=(m=%d,%s=%d) "
                     "figure=(row=%d,%s=%d)",
                     f.fig, ename(at), thr, x, j, e, m, sparse ? "kc" : "k", k, row.row,
                     sparse ? "kc" : "col", want_k);
              if (sparse) {
                // The chunk that compressed column kc belongs to lies inside the cell.
                const int lo = spec::sp_logical_k(at, k, 0);
                const int hi = spec::sp_logical_k(at, k, spec::sp_chunk_width(at) - 1);
                expect(t, lo >= col0 && hi < col0 + f.cell_cols,
                       "fig=%d type=%s t=%d a%d kc=%d chunk columns [%d,%d] cell columns [%d,%d)",
                       f.fig, ename(at), thr, x, k, lo, hi, col0, col0 + f.cell_cols);
              }
            }
          }
        }
      }
    }
  }
  report(t);
}

using DCoordFn = void (*)(int, int, int*, int*);

void check_d_fig(Test& t, const fig::DFig& f, EType at, int n, DCoordFn coord) {
  for (int ri = 0; ri < fig::kNumFragRows; ++ri) {
    const fig::FragRow& row = fig::kFragRows[ri];
    for (int bi = 0; bi < f.nblocks; ++bi) {
      const fig::DBlock& b = f.blocks[bi];
      const int col0 = b.col0_from_n ? n + b.col0 : b.col0;
      if (col0 < 0 || col0 + 4 * f.cell_cols > n) continue;  // block not drawn for this N
      const int first = (row.group == 0 ? b.top : b.bot) + (b.from_half ? n / 2 : 0);
      for (int q = 0; q < 4; ++q) {
        for (int s = 0; s < f.cell_elems; ++s) {
          const int thr = row.t_first + q;
          const int el = first + s;
          const int want_col = col0 + q * f.cell_cols + s;
          int m = -1, c = -1;
          coord(thr, el, &m, &c);
          expect(t, m == row.row && c == want_col,
                 "fig=%d type=%s n=%d t=%d d%d got=(m=%d,n=%d) figure=(row=%d,col=%d)", f.fig,
                 ename(at), n, thr, el, m, c, row.row, want_col);
        }
      }
    }
  }
}

