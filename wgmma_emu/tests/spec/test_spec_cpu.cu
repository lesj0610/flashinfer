      }
      expect(t, spec::valid_n(r.type, n) == listed, "type=%s n=%d valid_n=%d listed=%d",
             ename(r.type), n, spec::valid_n(r.type, n) ? 1 : 0, listed ? 1 : 0);
    }
  }
  report(t);
}

