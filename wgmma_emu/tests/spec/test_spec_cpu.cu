// Every CuTe operation family offers exactly the N that valid_n accepts.
void test_b_n_coverage() {
  Test t = make_test("b_trait_n_coverage");
  constexpr int kMaxGroups = 256;
  static char keys[kMaxGroups][96];
  static EType types[kMaxGroups];
  static uint32_t masks[kMaxGroups];
  int ngroups = 0;
  for (int i = 0; i < kNumTraitRows; ++i) {
    const TraitRow& r = kTraitRows[i];
    const char* p = strstr(r.name, "64x");
    const int pre = p ? static_cast<int>(p - r.name) + 3 : 0;
    const char* rest = r.name + pre;
    while (*rest >= '0' && *rest <= '9') ++rest;
    char key[96];
    snprintf(key, sizeof(key), "%.*sN%s", pre, r.name, rest);
    int gi = 0;
    while (gi < ngroups && strcmp(keys[gi], key) != 0) ++gi;
    if (gi == ngroups) {
      if (ngroups == kMaxGroups) {
        expect(t, false, "more than %d operation families", kMaxGroups);
        break;
      }
      snprintf(keys[gi], sizeof(keys[gi]), "%s", key);
      types[gi] = r.a;
      masks[gi] = 0;
      ++ngroups;
    }
    if (r.n % 8 == 0 && r.n >= 8 && r.n <= 256) masks[gi] |= 1u << (r.n / 8 - 1);
  }
  for (int gi = 0; gi < ngroups; ++gi) {
    uint32_t want = 0;
    for (int n = 8; n <= 256; n += 8) {
      if (spec::valid_n(types[gi], n)) want |= 1u << (n / 8 - 1);
    }
    expect(t, masks[gi] == want, "%s N mask cute=0x%08x valid_n=0x%08x", keys[gi], masks[gi], want);
  }
  report(t);
}

