// A: 128 x 256-byte tile at start, B: N x 256-byte tile at start + 32 KiB.
// The descriptor of tCrA(0, mi, ki) must address tCsA(_, mi, ki) element for
// element, and that tile must be sA(64 mi + m, K ki + k).
template <class Op, class T, bool MNA, bool MNB, int SW, int N>
void c2_case(Test& ta, Test& tb, uint32_t start) {
  constexpr int bits = cute::sizeof_bits_v<T>;
  constexpr int KTILE = 2048 / bits;
  using Tr = cute::MMA_Traits<Op>;
  constexpr int K = static_cast<int>(cute::get<2>(typename Tr::Shape_MNK{}));
  auto lA = cute::tile_to_shape(typename AtomOf<T, MNA, SW>::type{},
                                cute::make_shape(cute::Int<128>{}, cute::Int<KTILE>{}));
  auto lB = cute::tile_to_shape(typename AtomOf<T, MNB, SW>::type{},
                                cute::make_shape(cute::Int<N>{}, cute::Int<KTILE>{}));
  auto sA = cute::make_tensor(cute::make_smem_ptr(reinterpret_cast<T*>(g_arena + start)), lA);
  auto sB =
      cute::make_tensor(cute::make_smem_ptr(reinterpret_cast<T*>(g_arena + start + 0x8000u)), lB);
  auto mma = cute::make_tiled_mma(Op{});
  auto thr = mma.get_slice(0);
  auto tCsA = thr.partition_A(sA);
  auto tCsB = thr.partition_B(sB);
  auto tCrA = thr.partition_fragment_A(sA);
  auto tCrB = thr.partition_fragment_B(sB);

  const int vA = static_cast<int>(cute::size<0>(tCsA));
  const int mA = static_cast<int>(cute::size<1>(tCsA));
  const int kA = static_cast<int>(cute::size<2>(tCsA));
  expect(ta,
         vA == 64 * K && mA == 2 && kA == KTILE / K &&
             static_cast<int>(cute::size<1>(tCrA)) == mA &&
             static_cast<int>(cute::size<2>(tCrA)) == kA,
         "type=%s mn=(%d,%d) sw=%d n=%d tCsA (%d,%d,%d)", TName<T>::v, MNA ? 1 : 0, MNB ? 1 : 0, SW,
         N, vA, mA, kA);
  for (int mi = 0; mi < mA; ++mi) {
    for (int ki = 0; ki < kA; ++ki) {
      const cute::GmmaDescriptor dd = tCrA(0, mi, ki);
      const spec::Desc d = spec::decode_desc(dd.desc_);
      expect(ta, d.swizzle_bytes == SW && d.base_off == 0,
             "type=%s A sw=%d mi=%d ki=%d decoded sw=%d base_off=%u", TName<T>::v, SW, mi, ki,
             d.swizzle_bytes, d.base_off);
      for (int k = 0; k < K; ++k) {
        for (int m = 0; m < 64; ++m) {
          const uint32_t part = arena_off(&tCsA(m + 64 * k, mi, ki));
          const uint32_t tile = arena_off(&sA(64 * mi + m, K * ki + k));
          const uint32_t got = spec::smem_addr(d, MNA, bits, m, k);
          expect(ta, got == part && part == tile,
                 "type=%s A mn_major=%d sw=%d start=0x%x mi=%d ki=%d m=%d k=%d spec=0x%x "
                 "partition=0x%x tile=0x%x",
                 TName<T>::v, MNA ? 1 : 0, SW, start, mi, ki, m, k, got, part, tile);
        }
      }
    }
  }

  const int vB = static_cast<int>(cute::size<0>(tCsB));
  const int nB = static_cast<int>(cute::size<1>(tCsB));
  const int kB = static_cast<int>(cute::size<2>(tCsB));
  expect(tb,
         vB == N * K && nB == 1 && kB == KTILE / K && static_cast<int>(cute::size<1>(tCrB)) == nB &&
             static_cast<int>(cute::size<2>(tCrB)) == kB,
         "type=%s mn=(%d,%d) sw=%d n=%d tCsB (%d,%d,%d)", TName<T>::v, MNA ? 1 : 0, MNB ? 1 : 0, SW,
         N, vB, nB, kB);
  for (int ni = 0; ni < nB; ++ni) {
    for (int ki = 0; ki < kB; ++ki) {
      const cute::GmmaDescriptor dd = tCrB(0, ni, ki);
      const spec::Desc d = spec::decode_desc(dd.desc_);
      expect(tb, d.swizzle_bytes == SW && d.base_off == 0,
             "type=%s B sw=%d ni=%d ki=%d decoded sw=%d base_off=%u", TName<T>::v, SW, ni, ki,
             d.swizzle_bytes, d.base_off);
      for (int k = 0; k < K; ++k) {
        for (int n = 0; n < N; ++n) {
          const uint32_t part = arena_off(&tCsB(n + N * k, ni, ki));
          const uint32_t tile = arena_off(&sB(N * ni + n, K * ki + k));
          const uint32_t got = spec::smem_addr(d, MNB, bits, n, k);
          expect(tb, got == part && part == tile,
                 "type=%s B mn_major=%d sw=%d n_tile=%d start=0x%x ki=%d n=%d k=%d spec=0x%x "
                 "partition=0x%x tile=0x%x",
                 TName<T>::v, MNB ? 1 : 0, SW, N, start, ki, n, k, got, part, tile);
        }
      }
    }
  }
}

