template <class Op>
TraitInfo trait_info() {
  using Tr = cute::MMA_Traits<Op>;
  using VA = ValInfo<typename Tr::ValTypeA>;
  using VB = ValInfo<typename Tr::ValTypeB>;
  TraitInfo r{};
  r.m = static_cast<int>(cute::get<0>(typename Tr::Shape_MNK{}));
  r.n = static_cast<int>(cute::get<1>(typename Tr::Shape_MNK{}));
  r.k = static_cast<int>(cute::get<2>(typename Tr::Shape_MNK{}));
  r.a = ETypeOf<typename VA::raw>::value;
  r.b = ETypeOf<typename VB::raw>::value;
  r.d = ETypeOf<typename Tr::ValTypeD>::value;
  r.a_sparsity = VA::sparsity;
  r.b_sparsity = VB::sparsity;
  r.la = layout_fn<typename Tr::ALayout>();
  r.lb = layout_fn<typename Tr::BLayout>();
  r.lc = layout_fn<typename Tr::CLayout>();
  r.has_e = false;
  r.e_bits = 0;
  r.e_type = -1;
  r.le = LayoutFn{nullptr, 0, 0};
  if constexpr (HasE<Tr>::value) {
    using VE = ValInfo<typename Tr::ValTypeE>;
    r.has_e = true;
    r.e_bits = 8 / VE::sparsity;
    r.e_type = ETypeOf<typename VE::raw>::value;
    r.le = layout_fn<typename Tr::ELayout>();
  }
  return r;
}

