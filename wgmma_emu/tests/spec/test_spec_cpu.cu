// Independent Swizzle<B,4,3> on a byte address: XOR the 16-byte chunk index
// inside a W-byte row with the row index modulo W / 16.
uint32_t ref_swizzle(uint32_t a, int W) {
  if (W == 0) return a;
  const uint32_t chunks = static_cast<uint32_t>(W) / 16u;
  return a ^ (((a >> 7) % chunks) << 4);
}

bool desc_eq(const spec::Desc& a, const spec::Desc& b) {
  return a.start == b.start && a.lbo == b.lbo && a.sbo == b.sbo && a.base_off == b.base_off &&
         a.swizzle_bytes == b.swizzle_bytes;
}

uint64_t splitmix64(uint64_t& s) {
  uint64_t z = (s += 0x9E3779B97F4A7C15ull);
  z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
  z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
  return z ^ (z >> 31);
}

