struct Test {
  const char* name;
  long long cases;
  long long mismatches;
  int printed;
};

int g_fail = 0;
constexpr int kMaxPrinted = 8;

Test make_test(const char* name) { return Test{name, 0, 0, 0}; }

__attribute__((format(printf, 3, 4))) void expect(Test& t, bool ok, const char* fmt, ...) {
  ++t.cases;
  if (ok) return;
  ++t.mismatches;
  if (t.printed >= kMaxPrinted) return;
  ++t.printed;
  printf("WGEMU-MISMATCH name=%s ", t.name);
  va_list ap;
  va_start(ap, fmt);
  vprintf(fmt, ap);
  va_end(ap);
  printf("\n");
}

void report(const Test& t) {
  printf("WGEMU-TEST name=%s cases=%lld mismatches=%lld\n", t.name, t.cases, t.mismatches);
  if (t.cases == 0 || t.mismatches != 0) g_fail = 1;
}

const char* ename(EType e) {
  switch (e) {
    case EType::F16:
      return "f16";
    case EType::BF16:
      return "bf16";
    case EType::TF32:
      return "tf32";
    case EType::E4M3:
      return "e4m3";
    case EType::E5M2:
      return "e5m2";
    case EType::S8:
      return "s8";
    case EType::U8:
      return "u8";
    case EType::B1:
      return "b1";
    case EType::F32:
      return "f32";
    case EType::S32:
      return "s32";
  }
  return "?";
}

