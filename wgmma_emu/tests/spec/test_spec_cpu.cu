const uint64_t kDescMask =
    0x3FFFull | (0x3FFFull << 16) | (0x3FFFull << 32) | (0x7ull << 49) | (0x3ull << 62);

void test_d_desc_roundtrip() {
  Test t = make_test("d_desc_roundtrip");
  static const int kSw[4] = {0, 32, 64, 128};
  uint64_t seed = 0x5EED0001ull;
  for (int i = 0; i < 200000; ++i) {
    const uint64_t r = splitmix64(seed);
    const spec::Desc in{static_cast<uint32_t>(r & 0x3FFFu) << 4,
                        static_cast<uint32_t>((r >> 14) & 0x3FFFu) << 4,
                        static_cast<uint32_t>((r >> 28) & 0x3FFFu) << 4,
                        static_cast<uint32_t>((r >> 42) & 0x7u), kSw[(r >> 45) & 3u]};
    const uint64_t e = spec::encode_desc(in);
    const spec::Desc out = spec::decode_desc(e);
    expect(t, desc_eq(in, out) && (e & ~kDescMask) == 0,
           "start=0x%x lbo=0x%x sbo=0x%x base_off=%u sw=%d encoded=0x%016llx", in.start, in.lbo,
           in.sbo, in.base_off, in.swizzle_bytes, static_cast<unsigned long long>(e));
    const uint64_t raw = splitmix64(seed);
    const uint64_t back = spec::encode_desc(spec::decode_desc(raw));
    expect(t, back == (raw & kDescMask), "raw=0x%016llx re-encoded=0x%016llx",
           static_cast<unsigned long long>(raw), static_cast<unsigned long long>(back));
    // matrix-descriptor-encode(x) = (x & 0x3FFFF) >> 4 on unaligned / large byte values.
    const uint64_t w = splitmix64(seed);
    const uint32_t a = static_cast<uint32_t>(w), b = static_cast<uint32_t>(w >> 32),
                   c = static_cast<uint32_t>(w >> 13);
    const spec::Desc wide{a, b, c, 0u, 0};
    const spec::Desc dec = spec::decode_desc(spec::encode_desc(wide));
    expect(t, dec.start == (a & 0x3FFF0u) && dec.lbo == (b & 0x3FFF0u) && dec.sbo == (c & 0x3FFF0u),
           "encode of start=0x%x lbo=0x%x sbo=0x%x gave 0x%x 0x%x 0x%x", a, b, c, dec.start,
           dec.lbo, dec.sbo);
  }
  expect(t,
         spec::swizzle_code(0) == 0 && spec::swizzle_code(128) == 1 &&
             spec::swizzle_code(64) == 2 && spec::swizzle_code(32) == 3 &&
             spec::swizzle_code(16) == -1,
         "swizzle_code table");
  report(t);
}

void test_d_desc_vs_cute() {
  Test t = make_test("d_desc_vs_cute_bitfield");
  static const int kSwOfCode[4] = {0, 128, 64, 32};
  uint64_t seed = 0x5EED0002ull;
  for (int i = 0; i < 100000; ++i) {
    const uint64_t r = splitmix64(seed);
    const uint32_t s = static_cast<uint32_t>(r & 0x3FFFu);
    const uint32_t l = static_cast<uint32_t>((r >> 14) & 0x3FFFu);
    const uint32_t sb = static_cast<uint32_t>((r >> 28) & 0x3FFFu);
    const uint32_t bo = static_cast<uint32_t>((r >> 42) & 0x7u);
    const uint32_t code = static_cast<uint32_t>((r >> 45) & 0x3u);
    cute::GmmaDescriptor g;
    g.bitfield.start_address_ = static_cast<uint16_t>(s);
    g.bitfield.leading_byte_offset_ = static_cast<uint16_t>(l);
    g.bitfield.stride_byte_offset_ = static_cast<uint16_t>(sb);
    g.bitfield.base_offset_ = static_cast<uint8_t>(bo);
    g.bitfield.layout_type_ = static_cast<uint8_t>(code);
    const spec::Desc d{s << 4, l << 4, sb << 4, bo, kSwOfCode[code]};
    const uint64_t e = spec::encode_desc(d);
    expect(t, e == g.desc_ && desc_eq(spec::decode_desc(g.desc_), d),
           "fields (%u,%u,%u,%u,%u) spec=0x%016llx cute=0x%016llx", s, l, sb, bo, code,
           static_cast<unsigned long long>(e), static_cast<unsigned long long>(g.desc_));
  }
  using LT = cute::SM90::GMMA::LayoutType;
  expect(t,
         spec::swizzle_code(0) == static_cast<int>(LT::INTERLEAVE) &&
             spec::swizzle_code(128) == static_cast<int>(LT::B128) &&
             spec::swizzle_code(64) == static_cast<int>(LT::B64) &&
             spec::swizzle_code(32) == static_cast<int>(LT::B32),
         "swizzle_code vs cute LayoutType");
  report(t);
}

uint32_t cute_swizzle(uint32_t a, int W) {
  switch (W) {
    case 32:
      return static_cast<uint32_t>(cute::Swizzle<1, 4, 3>{}(a));
    case 64:
      return static_cast<uint32_t>(cute::Swizzle<2, 4, 3>{}(a));
    case 128:
      return static_cast<uint32_t>(cute::Swizzle<3, 4, 3>{}(a));
    default:
      return a;
  }
}

void test_d_swizzle_props() {
  Test t = make_test("d_swizzle_props");
  static const int kW[4] = {0, 32, 64, 128};
  for (int W : kW) {
    const uint32_t allowed = W != 0 ? ((static_cast<uint32_t>(W) / 16u - 1u) << 4) : 0u;
    for (uint32_t a = 0; a < (1u << 18); ++a) {
      const uint32_t s = spec::swizzle_addr(a, W, 0);
      const bool ok = spec::swizzle_addr(s, W, 0) == a && s == cute_swizzle(a, W) &&
                      s == ref_swizzle(a, W) && ((s ^ a) & ~allowed) == 0;
      expect(t, ok, "W=%d a=0x%x swizzled=0x%x cute=0x%x", W, a, s, cute_swizzle(a, W));
    }
  }
  report(t);
}

// [inferred] base_off != 0: a swizzle pattern that starts at P (a 128-byte
// multiple, not aligned to the pattern size 8 W) with base_off = (P >> 7) & 7
// (wgmma_spec.txt:874-893) swizzles relative to P.
void test_d_base_off_infer() {
  Test t = make_test("d_swizzle_base_off_infer");
  static const int kW[3] = {32, 64, 128};
  static const uint32_t kAtoms[3] = {0u, 5u, 100u};
  for (int W : kW) {
    for (uint32_t a : kAtoms) {
      for (uint32_t j = 0; j < 8; ++j) {
        const uint32_t P = 1024u * a + 128u * j;
        const uint32_t bo = (P >> 7) & 7u;
        for (uint32_t off = 0; off < 8u * static_cast<uint32_t>(W); ++off) {
          const uint32_t got = spec::swizzle_addr(P + off, W, bo);
          const uint32_t want = P + ref_swizzle(off, W);
          expect(t, got == want, "W=%d P=0x%x base_off=%u off=0x%x got=0x%x want=0x%x", W, P, bo,
                 off, got, want);
        }
        // K-major 16-bit operand whose pattern starts at P, SBO = 8 W.
        const uint32_t sbo = 8u * static_cast<uint32_t>(W);
        const spec::Desc d{P, 0u, sbo, bo, W};
        for (int mn = 0; mn < 16; ++mn) {
          for (int k = 0; k < W / 2; ++k) {
            const uint32_t off = static_cast<uint32_t>(mn % 8) * static_cast<uint32_t>(W) +
                                 static_cast<uint32_t>(mn / 8) * sbo +
                                 2u * static_cast<uint32_t>(k);
            const uint32_t got = spec::smem_addr(d, false, 16, mn, k);
            const uint32_t want = P + ref_swizzle(off, W);
            expect(t, got == want, "W=%d P=0x%x base_off=%u mn=%d k=%d got=0x%x want=0x%x", W, P,
                   bo, mn, k, got, want);
          }
        }
      }
    }
  }
  report(t);
}

