// The rule figure 158 draws: one column per cell, rows r + 8 (i % 2),
// columns 4 (i / 2) + q.
void fig158_coord(int t, int i, int* m, int* n) {
  const int tt = t & 127;
  const int w = tt >> 5, l = tt & 31, g = l >> 2, q = l & 3;
  *m = 16 * w + g + 8 * (i & 1);
  *n = 4 * (i >> 1) + q;
}

void test_fig158() {
  Test self = make_test("a_fig158_self");
  Test vs = make_test("a_fig158_vs_spec");
#if !defined(WGEMU_SPEC_STRICT_FIG158)
  vs.printed = kMaxPrinted;  // informational unless strict
#endif
  const fig::DFig& f = fig::kFig158;
  for (int ti = 0; ti < f.ntypes; ++ti) {
    for (int n = 8; n <= 256; n += 8) {
      if (!spec::valid_n(f.types[ti], n)) continue;
      check_d_fig(self, f, f.types[ti], n, &fig158_coord);
      check_d_fig(vs, f, f.types[ti], n, &spec_d_coord);
    }
  }
  report(self);
  int em = -1, en = -1;
  spec::d_frag_coord(0, 2, &em, &en);
  printf(
      "WGEMU-SPEC-CONFLICT name=a_fig158_vs_spec fig=158 cases=%lld differing=%lld "
      "example=\"figure row 0 col 4 is T0:d2, d_frag_coord(T0,d2) is row %d col %d\" "
      "resolution=\"spec.h keeps the D layout of figures 152/154/156 and CuTe CLayout_64xN for "
      "b1 [inferred]\"\n",
      vs.cases, vs.mismatches, em, en);
#if defined(WGEMU_SPEC_STRICT_FIG158)
  report(vs);
#endif
}

// Figure 158, row 15, column 7 prints T31:d1; the figure's own rule and
// d_frag_coord both put d3 there and d1 elsewhere.
void test_fig158_typo() {
  Test t = make_test("a_fig158_typo_note");
  const fig::DCellNote& c = fig::kFig158Typo;
  int m = -1, n = -1;
  fig158_coord(c.t, c.pattern_elem, &m, &n);
  expect(t, m == c.row && n == c.col, "fig158 rule d%d -> (%d,%d)", c.pattern_elem, m, n);
  fig158_coord(c.t, c.literal_elem, &m, &n);
  expect(t, !(m == c.row && n == c.col), "fig158 rule d%d -> (%d,%d)", c.literal_elem, m, n);
  spec::d_frag_coord(c.t, c.pattern_elem, &m, &n);
  expect(t, m == c.row && n == c.col, "d_frag_coord d%d -> (%d,%d)", c.pattern_elem, m, n);
  spec::d_frag_coord(c.t, c.literal_elem, &m, &n);
  expect(t, !(m == c.row && n == c.col), "d_frag_coord d%d -> (%d,%d)", c.literal_elem, m, n);
  printf(
      "WGEMU-SPEC-NOTE fig=%d row=%d col=%d cell=\"T%d:d%d\" figure_rule=d%d d_frag_coord=d%d "
      "(transcribed as d%d)\n",
      c.fig, c.row, c.col, c.t, c.literal_elem, c.pattern_elem, c.pattern_elem, c.pattern_elem);
  report(t);
}

// Figures 179/181/183/184.
void test_fig_meta() {
  Test t = make_test("a_fig_meta");
  bool covered[10][16] = {};
  for (int fi = 0; fi < fig::kNumMetaFigs; ++fi) {
    const fig::MetaFig& f = fig::kMetaFigs[fi];
    for (int ti = 0; ti < f.ntypes; ++ti) {
      const EType at = f.types[ti];
      expect(t, f.width == spec::sp_chunk_width(at), "fig=%d type=%s width=%d sp_chunk_width=%d",
             f.fig, ename(at), f.width, spec::sp_chunk_width(at));
      const int nsel = f.lane_plus_2sel ? 2 : 1;
      for (int sel = 0; sel < nsel; ++sel) {
        for (int w = 0; w < 4; ++w) {
          for (int ri = 0; ri < f.nrows; ++ri) {
            for (int c = 0; c < 8; ++c) {
              const fig::MetaCell& cell = f.cells[ri][c];
              const int m = 16 * w + f.rows[ri];
              const int chunk = f.chunk0 + c;
              int lane = -1, bit = -1;
              spec::sp_meta_loc(at, sel, m, chunk, &lane, &bit);
              const int want_lane = cell.lane + (f.lane_plus_2sel ? 2 * sel : 0);
              expect(t, lane == want_lane && bit == cell.lo && cell.hi == cell.lo + 3,
                     "fig=%d type=%s sel=%d m=%d chunk=%d spec=(lane %d, bit %d) "
                     "figure=(lane %d, bits %d..%d)",
                     f.fig, ename(at), sel, m, chunk, lane, bit, want_lane, cell.hi, cell.lo);
              covered[static_cast<int>(at)][chunk] = true;
            }
          }
        }
      }
    }
  }
  // Every chunk of a sparse row appears in some figure.
  for (EType at : kSparseTypes) {
    int count = 0;
    for (int c = 0; c < 16; ++c) count += covered[static_cast<int>(at)][c] ? 1 : 0;
    expect(t, count == spec::sp_meta_chunks(at), "type=%s figure chunks=%d sp_meta_chunks=%d",
           ename(at), count, spec::sp_meta_chunks(at));
  }
  report(t);
}

// Figures 174-177.
void test_fig_meta_example() {
  Test t = make_test("a_fig_meta_example");
  for (int xi = 0; xi < fig::kNumMetaExamples; ++xi) {
    const fig::MetaExample& x = fig::kMetaExamples[xi];
    for (int ti = 0; ti < x.ntypes; ++ti) {
      const EType at = x.types[ti];
      expect(t, x.width == spec::sp_chunk_width(at) && x.nnz == spec::sp_nnz_per_chunk(at),
             "fig=%d type=%s width=%d nnz=%d", x.fig, ename(at), x.width, x.nnz);
      expect(t, spec::sp_meta_valid(at, x.field), "fig=%d type=%s field=0x%x invalid", x.fig,
             ename(at), x.field);
      int idx0 = -9, idx1 = -9;
      spec::sp_meta_decode(at, x.field, &idx0, &idx1);
      // Chunk element p (p = 0 lowest) is chunk_hi_to_lo[width - 1 - p].
      const int lo_val = x.operand_hi_to_lo[x.nnz - 1];
      expect(t,
             idx0 >= 0 && idx0 < x.width && x.chunk_hi_to_lo[x.width - 1 - idx0] == lo_val &&
                 spec::sp_logical_k(at, 0, idx0) == idx0,
             "fig=%d type=%s field=0x%x idx0=%d", x.fig, ename(at), x.field, idx0);
      if (x.nnz == 2) {
        const int hi_val = x.operand_hi_to_lo[0];
        expect(t,
               idx1 >= 0 && idx1 < x.width && x.chunk_hi_to_lo[x.width - 1 - idx1] == hi_val &&
                   spec::sp_logical_k(at, 1, idx1) == idx1,
               "fig=%d type=%s field=0x%x idx1=%d", x.fig, ename(at), x.field, idx1);
      } else {
        expect(t, idx1 == -1, "fig=%d type=%s field=0x%x idx1=%d", x.fig, ename(at), x.field, idx1);
      }
      for (int p = 0; p < x.width; ++p) {
        if (p == idx0 || p == idx1) continue;
        expect(t, x.chunk_hi_to_lo[x.width - 1 - p] == 0,
               "fig=%d type=%s element %d not selected but non-zero", x.fig, ename(at), p);
      }
    }
  }
  report(t);
}

const uint32_t kFigStarts[] = {0u, 0x400u, 0x3E000u};

// Figures 159-173: every element of every 16-byte chunk drawn.
void test_fig_smem() {
  Test t = make_test("a_fig_smem");
  for (int fi = 0; fi < fig::kNumSmemFigs; ++fi) {
    const fig::SmemFig& f = fig::kSmemFigs[fi];
    const int eb = f.elem_bits / 8;
    const int per_chunk = 16 / eb;
    for (uint32_t start : kFigStarts) {
      const spec::Desc d{start, f.lbo, f.sbo, 0u, f.swizzle_bytes};
      for (int ri = 0; ri < f.nrows; ++ri) {
        for (int ci = 0; ci < f.ncols; ++ci) {
          for (int i = 0; i < per_chunk; ++i) {
            const int mn = f.row_mn[ri] + (f.mn_major ? i : 0);
            const int k = f.col_k[ci] + (f.mn_major ? 0 : i);
            const uint32_t want =
                start + static_cast<uint32_t>(f.value[ri][ci] * f.value_unit_bytes + i * eb);
            const uint32_t got = spec::smem_addr(d, f.mn_major, f.elem_bits, mn, k);
            expect(t, got == want, "fig=%d start=0x%x mn=%d k=%d spec=0x%x figure=0x%x", f.fig,
                   start, mn, k, got, want);
          }
        }
      }
    }
  }
  report(t);
}

int colex_offset(int idx, int n, const int* shape, const int* stride) {
  int off = 0;
  for (int i = 0; i < n; ++i) {
    off += (idx % shape[i]) * stride[i];
    idx /= shape[i];
  }
  return off;
}

// "Exact layout" lines of the examples for figures 169-173.
void test_fig_smem_exact() {
  Test t = make_test("a_fig_smem_exact");
  for (int xi = 0; xi < fig::kNumExactLayouts; ++xi) {
    const fig::ExactLayout& x = fig::kExactLayouts[xi];
    int rows = 1, cols = 1;
    for (int i = 0; i < x.nr; ++i) rows *= x.rshape[i];
    for (int i = 0; i < x.nc; ++i) cols *= x.cshape[i];
    const int eb = x.elem_bits / 8;
    for (uint32_t start : kFigStarts) {
      const spec::Desc d{start, x.lbo, x.sbo, 0u, x.swizzle_bytes};
      for (int mn = 0; mn < rows; ++mn) {
        for (int k = 0; k < cols; ++k) {
          const int elems = colex_offset(mn, x.nr, x.rshape, x.rstride) +
                            colex_offset(k, x.nc, x.cshape, x.cstride);
          const uint32_t want =
              ref_swizzle(start + static_cast<uint32_t>(elems * eb), x.swizzle_bytes);
          const uint32_t got = spec::smem_addr(d, x.mn_major, x.elem_bits, mn, k);
          expect(t, got == want, "fig=%d start=0x%x mn=%d k=%d spec=0x%x exact=0x%x", x.fig, start,
                 mn, k, got, want);
        }
      }
    }
  }
  report(t);
}

