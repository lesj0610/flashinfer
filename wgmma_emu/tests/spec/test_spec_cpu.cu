// Swizzle-aligned shared-memory start offsets (1 KiB multiples).
const uint32_t kStarts[] = {0x400u, 0x8000u, 0x12400u};

// One K tile of 256 bytes, sliced into KI-element k-blocks; each slice goes
// through make_gmma_desc like a CuTe mainloop would.
template <class T, bool MN, int SW, int MNSIZE, int KI>
void c1_tile(Test& t, uint32_t start) {
  constexpr int bits = cute::sizeof_bits_v<T>;
  constexpr int KTILE = 2048 / bits;
  constexpr auto kMajor = MN ? cute::SM90::GMMA::Major::MN : cute::SM90::GMMA::Major::K;
  auto layout = cute::tile_to_shape(typename AtomOf<T, MN, SW>::type{},
                                    cute::make_shape(cute::Int<MNSIZE>{}, cute::Int<KTILE>{}));
  auto s = cute::make_tensor(cute::make_smem_ptr(reinterpret_cast<T*>(g_arena + start)), layout);
  for (int kb = 0; kb < KTILE / KI; ++kb) {
    auto sk = cute::local_tile(s, cute::make_shape(cute::Int<MNSIZE>{}, cute::Int<KI>{}),
                               cute::make_coord(0, kb));
    const cute::GmmaDescriptor desc = cute::SM90::GMMA::make_gmma_desc<kMajor>(sk);
    const spec::Desc d = spec::decode_desc(desc.desc_);
    const uint32_t origin = arena_off(cute::raw_pointer_cast(sk.data()));
    expect(t, d.swizzle_bytes == SW && d.base_off == 0 && d.start == (origin & 0x3FFF0u),
           "type=%s mn_major=%d sw=%d mnsize=%d ki=%d start=0x%x kb=%d decoded sw=%d base_off=%u "
           "start=0x%x origin=0x%x",
           TName<T>::v, MN ? 1 : 0, SW, MNSIZE, KI, start, kb, d.swizzle_bytes, d.base_off, d.start,
           origin);
    for (int mn = 0; mn < MNSIZE; ++mn) {
      for (int k = 0; k < KI; ++k) {
        const uint32_t want = arena_off(&sk(mn, k));
        const uint32_t got = spec::smem_addr(d, MN, bits, mn, k);
        expect(t, got == want,
               "type=%s mn_major=%d sw=%d mnsize=%d ki=%d start=0x%x kb=%d mn=%d k=%d "
               "spec=0x%x cute=0x%x",
               TName<T>::v, MN ? 1 : 0, SW, MNSIZE, KI, start, kb, mn, k, got, want);
      }
    }
  }
}

// MN extents: one and three layout atoms. K slices: 32 bytes (dense A/B,
// sparse A K-major) and 64 bytes (sparse B); MN-major also 16 bytes (sparse
// A) when that is a whole number of 8-element k groups. K-major 32B-swizzle
// with 64-byte slices is left out: its second 32-byte column lies in another
// atom and spec.h's linear continuation is [inferred] (see smem_addr).
template <class T, bool MN, int SW>
void c1_major_sw(Test& t) {
  constexpr int eb = cute::sizeof_bits_v<T> / 8;
  constexpr int atom_mn = MN ? (SW != 0 ? SW / eb : 16 / eb) : 8;
  for (uint32_t start : kStarts) {
    c1_tile<T, MN, SW, atom_mn, 32 / eb>(t, start);
    c1_tile<T, MN, SW, 3 * atom_mn, 32 / eb>(t, start);
    if constexpr (MN || SW != 32) {
      c1_tile<T, MN, SW, atom_mn, 64 / eb>(t, start);
      c1_tile<T, MN, SW, 3 * atom_mn, 64 / eb>(t, start);
    }
    if constexpr (MN && (16 / eb) % 8 == 0) {
      c1_tile<T, MN, SW, atom_mn, 16 / eb>(t, start);
      c1_tile<T, MN, SW, 3 * atom_mn, 16 / eb>(t, start);
    }
  }
}

template <class T>
void c1_type(Test& t) {
  c1_major_sw<T, false, 0>(t);
  c1_major_sw<T, false, 32>(t);
  c1_major_sw<T, false, 64>(t);
  c1_major_sw<T, false, 128>(t);
  c1_major_sw<T, true, 0>(t);
  c1_major_sw<T, true, 32>(t);
  c1_major_sw<T, true, 64>(t);
  c1_major_sw<T, true, 128>(t);
}

