// ELayout value v covers metadata bits [v * e_bits, (v + 1) * e_bits) of the
// thread's metadata register.
void test_b_elayout() {
  Test t = make_test("b_elayout_vs_sp_meta_loc");
  for (int i = 0; i < kNumTraitRows; ++i) {
    const TraitRow& r = kTraitRows[i];
    if (!r.sparse) continue;
    const TraitInfo& ti = g_infos[i];
    const LayoutFn& L = ti.le;
    expect(t, L.eval != nullptr && L.nthr == 128 && L.nval * ti.e_bits == 32,
           "%s ELayout %dx%d e_bits=%d", r.name, L.nthr, L.nval, ti.e_bits);
    if (L.eval == nullptr || L.nval * ti.e_bits != 32) continue;
    const int width = spec::sp_chunk_width(r.a);
    for (int th = 0; th < 128; ++th) {
      // 8-bit: every lane holds metadata, sel = 0. f16/bf16/tf32: lanes 2,3 of
      // each quad hold it for sel = 1 (ELayout gives them stride 0).
      const int sel = wgemu::etype_bits(r.a) == 8 ? 0 : (((th & 31) >> 1) & 1);
      for (int v = 0; v < L.nval; ++v) {
        const int idx = L.eval(th, v);
        const int m = idx % 64, k = idx / 64;
        int lane = -1, bit = -1;
        spec::sp_meta_loc(r.a, sel, m, k / width, &lane, &bit);
        expect(t, 32 * (m / 16) + lane == th && bit + (k % width) * ti.e_bits == v * ti.e_bits,
               "%s t=%d v=%d cute=(m=%d,k=%d) spec=(thread %d, bit %d + %d)", r.name, th, v, m, k,
               32 * (m / 16) + lane, bit, (k % width) * ti.e_bits);
      }
    }
  }
  report(t);
}

