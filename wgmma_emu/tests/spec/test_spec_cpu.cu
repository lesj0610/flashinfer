// ---------------------------------------------------------------------------
// Host stand-in for shared memory
// ---------------------------------------------------------------------------
// make_gmma_desc() reads the start address through cute::cast_smem_ptr_to_uint,
// which has no host implementation. In the host pass it is routed through
// __nvvm_get_smem_pointer (the CUDA 10.2 branch of cute/arch/util.hpp; CuTe
// declares that intrinsic only for CUDA 10.2, and no CUDA 11+ header that this
// file includes declares it) and returns the offset inside g_arena. CuTe's
// swizzle_ptr swizzles absolute host addresses; the 4 KiB arena alignment
// makes that equal to swizzling the arena offset.
alignas(4096) static unsigned char g_arena[1u << 19];

static inline uint32_t arena_off(const void* p) {
  return static_cast<uint32_t>(reinterpret_cast<uintptr_t>(p) -
                               reinterpret_cast<uintptr_t>(g_arena));
}

#if !defined(__CUDA_ARCH__)
#define CUTE_NVVM_GET_SMEM_POINTER_ACTIVATED 1
extern "C" uint32_t __nvvm_get_smem_pointer(void const* p) { return arena_off(p); }
#endif

